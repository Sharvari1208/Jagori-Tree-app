-- Run this in your Supabase Dashboard: SQL Editor -> New Query -> Run

-- 1. Create the Trees table
CREATE TABLE IF NOT EXISTS public.trees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tree_id TEXT UNIQUE NOT NULL,
    species TEXT NOT NULL,
    plantation_date DATE NOT NULL,
    latitude TEXT NOT NULL,
    longitude TEXT NOT NULL,
    donor_name TEXT,
    village TEXT,
    tree_photo_url TEXT,
    height TEXT,
    girth TEXT,
    last_inspection DATE,
    survival_status TEXT DEFAULT 'Healthy',
    public_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create index for fast Tree ID lookups
CREATE INDEX IF NOT EXISTS idx_trees_tree_id ON public.trees (tree_id);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.trees ENABLE ROW LEVEL SECURITY;

-- 4. Create Policies allowing Public / Mobile Access:
-- Allow anyone to read trees (for public QR code verification and listing)
CREATE POLICY "Allow public read access"
ON public.trees
FOR SELECT
USING (true);

-- Allow anyone to insert trees from the field app
CREATE POLICY "Allow public insert access"
ON public.trees
FOR INSERT
WITH CHECK (true);

-- Allow updates (for field inspections & growth tracking)
CREATE POLICY "Allow public update access"
ON public.trees
FOR UPDATE
USING (true);

-- Allow delete (for removing test or erroneous tree records)
CREATE POLICY "Allow public delete access"
ON public.trees
FOR DELETE
USING (true);

-- 5. Enable Realtime Replication for instant live updates on QR pages
ALTER PUBLICATION supabase_realtime ADD TABLE public.trees;

